// Lab 6 - Task 7: Alphabets in ascending then descending order
// Displays A to Z then Z to A using loop

#include <iostream>
using namespace std;
int main()
{
	cout<<"Alphabets in ascending order\n";
	char ch='A';
	while(ch<='Z')
	{ cout<<ch<<" ";
	ch++;
	}
	
	cout<<"\nAlphabets in descending order\n";
	ch='Z';
	while(ch>='A')
	{ cout<<ch<<" ";
	ch--;
	}
	
	
	
	
	
	
	
	
	
	
	
}

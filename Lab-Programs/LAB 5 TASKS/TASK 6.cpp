// Lab 5 - Task 6: Compare Two Numbers
// Takes two numbers and tells which is greater or if both are equal

#include <iostream>
using namespace std;
int main()
{
	int x,y;
	cout<<"Enter 2 numbers: ";
	cin>>x>>y;
	
	if (x>y)
	{ cout<<"First one is greater"; }
	
	else if (x<y)
	{ cout<<"Second one is greater"; }
	
	else
	{ cout<<"Both are equal"; }	
	
	
	
	
	
	
	
	
}

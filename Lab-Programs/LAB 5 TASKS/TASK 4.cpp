// Lab 5 - Task 4: Positive, Negative or Zero
// Takes a number from user and tells if it is positive, negative or zero

#include <iostream>
using namespace std;
int main()
{
	int num;
	cout<<"Enter a number: ";
	cin>>num;
	
	if (num>0)
	{ cout<<num<<" is Positive"; }
	
	else if (num<0)
	{ cout<<num<<" is Negative"; }
	
	else
	{ cout<<num<<" is Zero"; }
	
	
	
	
	
	
	
	
	
}
